	ADCS R23, R15, R15
	ADCS R24, R16, R16
	ADCS ZR, R17, R17
	ADCS ZR, R19, R19
	ADC ZR, R20, R20
	UMULH R3, R7, R21
	UMULH R4, R7, R22
	UMULH R5, R7, R23
