	MUL R7, R4, R1
	UMULH R7, R4, R2
	ADDS R1, R12, R12
	ADCS R2, R13, R13
	ADC ZR, R14, R14
	MUL R9, R5, R15
	UMULH R9, R5, R25
	MUL R10, R5, R24
	UMULH R10, R5, R0
	MUL R10, R6, R17
	UMULH R10, R6, R19
	ADDS R24, R25, R16
	ADCS R0, R17, R17
	ADC ZR, R19, R19
	MUL R9, R6, R24
	UMULH R9, R6, R0
	ADDS R24, R16, R16
	ADCS R0, R17, R17
	ADC ZR, R19, R19
	// M = x_lo·y_hi + x_hi·y_lo (five words).
