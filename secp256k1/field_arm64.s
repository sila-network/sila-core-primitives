	MOVD ZR, R20
	// Row 0.
	MUL R25, R11, R7
	MUL R3, R7, R21
	MUL R4, R7, R22
	MUL R5, R7, R23
	MUL R6, R7, R24
	ADDS R21, R11, R11
	ADCS R22, R12, R12
	ADCS R23, R13, R13
	ADCS R24, R14, R14
	ADCS ZR, R15, R15
	ADCS ZR, R16, R16
	ADCS ZR, R17, R17
	ADCS ZR, R19, R19
	ADC ZR, R20, R20
	UMULH R3, R7, R21
	UMULH R4, R7, R22
	UMULH R5, R7, R23
	UMULH R6, R7, R24
	ADDS R21, R12, R12
	ADCS R22, R13, R13
	ADCS R23, R14, R14
	ADCS R24, R15, R15
	ADCS ZR, R16, R16
	ADCS ZR, R17, R17
	ADCS ZR, R19, R19
	ADC ZR, R20, R20
	// Row 1.
	MUL R25, R12, R7
	MUL R3, R7, R21
	MUL R4, R7, R22
	MUL R5, R7, R23
	MUL R6, R7, R24
	ADDS R21, R12, R12
	ADCS R22, R13, R13
	ADCS R23, R14, R14
	ADCS R24, R15, R15
	ADCS ZR, R16, R16
	ADCS ZR, R17, R17
	ADCS ZR, R19, R19
	ADC ZR, R20, R20
	UMULH R3, R7, R21
	UMULH R4, R7, R22
	UMULH R5, R7, R23
	UMULH R6, R7, R24
	ADDS R21, R13, R13
	ADCS R22, R14, R14
	ADCS R23, R15, R15
	ADCS R24, R16, R16
	ADCS ZR, R17, R17
	ADCS ZR, R19, R19
