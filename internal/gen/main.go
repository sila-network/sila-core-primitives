package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
)

func main() {
	out := flag.String("out", "", "output file")
	mode := flag.String("mode", "go", "go | asm")
	flag.Parse()

	var src []byte
	switch *mode {
	case "go":
		src = genGo()
	case "asm":
		src = genAsm()
	default:
		log.Fatalf("unknown mode %q", *mode)
	}
	if *out == "" {
		os.Stdout.Write(src)
		return
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

const header = "// SPDX-License-Identifier: Apache-2.0\n\n// Code generated by internal/gen from the Keccak specification. DO NOT EDIT.\n\n"

// goVariant selects the shape of the portable permutation; see genGo.
var goVariant = flag.String("variant", "mem", "locals | mem | mem-fusedc")

// genGo emits a portable permutation with two rounds per loop iteration that
// ping-pong between two lane sets (A -> E -> A), with lane complementing so
// χ needs only one NOT per plane. Variants:
//
//	locals:     lanes held in 50 local variables (compiler allocates/spills)
//	mem:        lanes addressed in place in a[] and a stack array e[]
//	mem-fusedc: like mem, but next round's θ column parities are
//	            accumulated while χ writes each lane
func genGo() []byte {
	var b bytes.Buffer
	p := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }

	rho := rhoOffsets()
	bMask := roundMasks()
	mem := *goVariant != "locals"
	fused := *goVariant == "mem-fusedc"
	lane := func(set string, i int) string {
		if mem {
			return fmt.Sprintf("%s[%d]", set, i)
		}
		return fmt.Sprintf("%s%d", set, i)
	}

	p(header)
	p("package keccak\n\nimport \"math/bits\"\n\n")
	p("// roundConstant holds RC[0..23] of Keccak-f[1600], computed by the\n")
	p("// generator from the specification's LFSR rc(t).\n")
	p("var roundConstant = [24]uint64{\n")
	for i, c := range roundConstants() {
		p("0x%016x, // RC[%d]\n", c, i)
	}
	p("}\n\n")
	p("// permuteGeneric applies the 24 rounds of Keccak-f[1600] to a.\n")
	p("// Lanes 1, 2, 8, 12, 17 and 20 are held inverted between rounds\n")
	p("// (lane complementing) and restored before returning.\n")
	p("// Generator variant: %s.\n", *goVariant)
	p("func permuteGeneric(a *[25]uint64) {\n")
	if mem {
		for i := 0; i < 25; i++ {
			if complemented[i] {
				p("a[%d] = ^a[%d]\n", i, i)
			}
		}
		p("var e [25]uint64\n")
	} else {
		for i := 0; i < 25; i++ {
			if complemented[i] {
				p("a%d := ^a[%d]\n", i, i)
			} else {
				p("a%d := a[%d]\n", i, i)
			}
		}
		p("var ")
		for i := 0; i < 25; i++ {
			if i > 0 {
				p(", ")
			}
			p("e%d", i)
		}
		p(" uint64\n")
	}
	if fused {
		for x := 0; x < 5; x++ {
			p("c%d := a[%d] ^ a[%d] ^ a[%d] ^ a[%d] ^ a[%d]\n", x, x, x+5, x+10, x+15, x+20)
		}
	}
	p("for r := 0; r < 24; r += 2 {\n")
	p("rc := (*[2]uint64)(roundConstant[r : r+2])\n")

	round := func(src, dst string, rcIdx int) {
		p("{\n")
		if !fused {
			for x := 0; x < 5; x++ {
				p("c%d := %s ^ %s ^ %s ^ %s ^ %s\n", x, lane(src, x), lane(src, x+5),
					lane(src, x+10), lane(src, x+15), lane(src, x+20))
			}
		}
		for x := 0; x < 5; x++ {
			p("d%d := c%d ^ bits.RotateLeft64(c%d, 1)\n", x, mod5(x-1), mod5(x+1))
		}
		for Y := 0; Y < 5; Y++ {
			p("{\n")
			for X := 0; X < 5; X++ {
				x, y := piSource(X, Y)
				s := laneIndex(x, y)
				if rho[s] == 0 {
					p("b%d := %s ^ d%d\n", X, lane(src, s), x)
				} else {
					p("b%d := bits.RotateLeft64(%s^d%d, %d)\n", X, lane(src, s), x, rho[s])
				}
			}
			for X := 0; X < 5; X++ {
				o := laneIndex(X, Y)
				f := findChi(bMask[laneIndex(X, Y)], bMask[laneIndex(X+1, Y)],
					bMask[laneIndex(X+2, Y)], complemented[o])
				e := f.expr(fmt.Sprintf("b%d", X), fmt.Sprintf("b%d", mod5(X+1)), fmt.Sprintf("b%d", mod5(X+2)))
				if o == 0 {
					e = "(" + e + fmt.Sprintf(") ^ rc[%d]", rcIdx)
				}
				if fused {
					p("v%d := %s\n", X, e)
				} else {
					p("%s = %s\n", lane(dst, o), e)
				}
			}
			if fused {
				for X := 0; X < 5; X++ {
					p("%s = v%d\n", lane(dst, laneIndex(X, Y)), X)
				}
				for X := 0; X < 5; X++ {
					if Y == 0 {
						p("n%d := v%d\n", X, X)
					} else {
						p("n%d ^= v%d\n", X, X)
					}
				}
			}
			p("}\n")
		}
		if fused {
			p("c0, c1, c2, c3, c4 = n0, n1, n2, n3, n4\n")
		}
		p("}\n")
	}
	if fused {
		// n0..n4 must outlive the plane blocks: declare per round.
		roundFused := func(src, dst string, rcIdx int) {
			p("{\nvar n0, n1, n2, n3, n4 uint64\n")
			b2 := b.Len()
			round(src, dst, rcIdx)
			// Plane 0 declared n's with :=; turn into assignments.
			out := b.Bytes()[b2:]
			fixed := bytes.ReplaceAll(out, []byte(" := v"), []byte(" = v"))
			b.Truncate(b2)
			b.Write(fixed)
			p("}\n")
		}
		roundFused("a", "e", 0)
		roundFused("e", "a", 1)
	} else {
		round("a", "e", 0)
		round("e", "a", 1)
	}
	p("}\n")
	for i := 0; i < 25; i++ {
		switch {
		case mem && complemented[i]:
			p("a[%d] = ^a[%d]\n", i, i)
		case !mem && complemented[i]:
			p("a[%d] = ^a%d\n", i, i)
		case !mem:
			p("a[%d] = a%d\n", i, i)
		}
	}
	p("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("format: %v\n%s", err, b.Bytes())
	}
	return src
}
