package main

import (
	"bytes"
	"fmt"
)

// genAsm emits an amd64 AVX-512VL permutation in which every one of the 25
// lanes lives in its own XMM register for all 24 rounds:
//
//   - π costs nothing: it is a renaming of registers done by this generator;
//   - θ uses one VPTERNLOGQ per lane (lane ^ C[x-1] ^ rol(C[x+1],1));
//   - χ uses one VPTERNLOGQ per lane (b0 ^ (^b1 & b2));
//   - ρ uses one VPROLQ per lane.
//
// Only the low 64 bits of each register are meaningful. X15 is never used
// because Go's internal ABI reserves it as a zero register.
func genAsm() []byte {
	var b bytes.Buffer
	p := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }

	var free []string
	for i := 31; i >= 0; i-- {
		if i != 15 {
			free = append(free, fmt.Sprintf("X%d", i))
		}
	}
	alloc := func() string {
		r := free[len(free)-1]
		free = free[:len(free)-1]
		return r
	}
	release := func(r string) { free = append(free, r) }

	p("// SPDX-License-Identifier: Apache-2.0\n\n")
	p("// Code generated by internal/gen from the Keccak specification. DO NOT EDIT.\n\n")
	p("//go:build amd64 && !purego\n\n")
	p("#include \"textflag.h\"\n\n")

	// permuteAVX512: one permutation of the state at a.
	p("// func permuteAVX512(a *[25]uint64)\n")
	p("TEXT ·permuteAVX512(SB), NOSPLIT, $0-8\n")
	p("\tMOVQ a+0(FP), DI\n")
	var lane [25]string
	for i := range lane {
		lane[i] = alloc()
		p("\tVMOVQ %d(DI), %s\n", 8*i, lane[i])
	}
	start := lane
	emitRounds(p, &lane, alloc, release)
	if lane != start {
		panic("register mapping not restored after 24 rounds")
	}
	for i := range lane {
		p("\tVMOVQ %s, %d(DI)\n", lane[i], 8*i)
	}
	clearRegs(p)
	p("\tRET\n\n")

	// absorbAVX512: XOR n consecutive 136-byte blocks from p into the
	// state, permuting after each one, without leaving registers.
	// Each lane is read with an exact 8-byte broadcast load, so no byte
	// outside the n*136-byte input is ever touched.
	p("// func absorbAVX512(a *[25]uint64, p *byte, n int)\n")
	p("TEXT ·absorbAVX512(SB), NOSPLIT, $0-24\n")
	p("\tMOVQ a+0(FP), DI\n\tMOVQ p+8(FP), SI\n\tMOVQ n+16(FP), CX\n")
	for i := range lane {
		p("\tVMOVQ %d(DI), %s\n", 8*i, lane[i])
	}
	p("\tTESTQ CX, CX\n\tJZ done\n")
	p("loop:\n")
	for i := 0; i < 17; i++ {
		p("\tVPXORQ.BCST %d(SI), %s, %s\n", 8*i, lane[i], lane[i])
	}
	emitRounds(p, &lane, alloc, release)
	if lane != start {
		panic("register mapping not restored after 24 rounds")
	}
	p("\tADDQ $136, SI\n\tDECQ CX\n\tJNZ loop\n")
	p("done:\n")
	for i := range lane {
		p("\tVMOVQ %s, %d(DI)\n", lane[i], 8*i)
	}
	clearRegs(p)
	p("\tRET\n")
	return b.Bytes()
}

// emitRounds emits the 24 rounds for the lane->register mapping in lane,
// updating the mapping as π renames registers.
func emitRounds(p func(string, ...any), lanePtr *[25]string, alloc func() string, release func(string)) {
	rho := rhoOffsets()
	xor3 := ternImm(func(a, b, c bool) bool { return a != b != c })
	chi := ternImm(func(a, b, c bool) bool { return a != (!b && c) })
	lane := *lanePtr
	for r := 0; r < 24; r++ {
		p("\n\t// round %d\n", r)
		// θ: column parities C[x].
		var c [5]string
		for x := 0; x < 5; x++ {
			c[x] = alloc()
			p("\tVMOVDQA64 %s, %s\n", lane[x], c[x])
			p("\tVPTERNLOGQ $0x%02x, %s, %s, %s\n", xor3, lane[x+10], lane[x+5], c[x])
			p("\tVPTERNLOGQ $0x%02x, %s, %s, %s\n", xor3, lane[x+20], lane[x+15], c[x])
		}
		// θ: lane ^= C[x-1] ^ rol(C[x+1], 1), fused into one ternary op.
		t := alloc()
		for x := 0; x < 5; x++ {
			p("\tVPROLQ $1, %s, %s\n", c[mod5(x+1)], t)
			for y := 0; y < 5; y++ {
				l := lane[laneIndex(x, y)]
				p("\tVPTERNLOGQ $0x%02x, %s, %s, %s\n", xor3, t, c[mod5(x-1)], l)
			}
		}
		release(t)
		for x := 4; x >= 0; x-- {
			release(c[x])
		}
		// ρ: rotate each lane in place.
		for i := 1; i < 25; i++ {
			p("\tVPROLQ $%d, %s, %s\n", rho[i], lane[i], lane[i])
		}
		// π: pure register renaming.
		var bl [25]string
		for X := 0; X < 5; X++ {
			for Y := 0; Y < 5; Y++ {
				x, y := piSource(X, Y)
				bl[laneIndex(X, Y)] = lane[laneIndex(x, y)]
			}
		}
		lane = bl
		// χ: per plane, keep copies of b0 and b1 which are overwritten
		// before their last use, then update all five lanes in place.
		for Y := 0; Y < 5; Y++ {
			row := lane[5*Y : 5*Y+5]
			s0, s1 := alloc(), alloc()
			p("\tVMOVDQA64 %s, %s\n", row[0], s0)
			p("\tVMOVDQA64 %s, %s\n", row[1], s1)
			ops := [5][3]string{
				{row[0], row[1], row[2]},
				{row[1], row[2], row[3]},
				{row[2], row[3], row[4]},
				{row[3], row[4], s0},
				{row[4], s0, s1},
			}
			for _, o := range ops {
				// Go operand order: imm, src3, src2, dst(=src1).
				p("\tVPTERNLOGQ $0x%02x, %s, %s, %s\n", chi, o[2], o[1], o[0])
			}
			release(s1)
			release(s0)
		}
		// ι: XOR the round constant (8-byte broadcast load) into lane 0.
		p("\tVPXORQ.BCST ·roundConstant+%d(SB), %s, %s\n", 8*r, lane[0], lane[0])
	}

	*lanePtr = lane
}

// ternImm builds a VPTERNLOGQ immediate: bit (a<<2 | b<<1 | c) holds f(a,b,c),
// where a is the destination operand, b the second and c the third source.
func ternImm(f func(a, b, c bool) bool) int {
	imm := 0
	for i := 0; i < 8; i++ {
		if f(i&4 != 0, i&2 != 0, i&1 != 0) {
			imm |= 1 << i
		}
	}
	return imm
}

// clearRegs zeroes every vector register the permutation used so no state
// (which may be derived from secret input) survives the call. Zeroing
// X0-X15 with VZEROALL also clears the upper halves, avoiding SSE/AVX
// transition penalties; X16-X31 are cleared individually.
func clearRegs(p func(string, ...any)) {
	p("\tVZEROALL\n")
	for i := 16; i < 32; i++ {
		p("\tVPXORQ X%d, X%d, X%d\n", i, i, i)
	}
}
